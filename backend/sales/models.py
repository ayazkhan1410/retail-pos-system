from django.conf import settings
from django.db import models
from django.db.models import Q

from audit.models import AppendOnlyModel
from inventory.models import Branch, Product


class Terminal(models.Model):
    branch = models.ForeignKey(Branch, on_delete=models.PROTECT)
    code = models.CharField(max_length=10)
    name = models.CharField(max_length=50)
    active = models.BooleanField(default=True)
    last_invoice_seq = models.PositiveIntegerField(default=0)

    class Meta:
        constraints = [models.UniqueConstraint(fields=['branch', 'code'], name='unique_terminal_per_branch')]
        ordering = ['code']

    def __str__(self):
        return self.name


class Shift(models.Model):
    terminal = models.ForeignKey(Terminal, on_delete=models.PROTECT)
    opened_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name='+')
    closed_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, on_delete=models.PROTECT, related_name='+')
    opened_at = models.DateTimeField(auto_now_add=True)
    closed_at = models.DateTimeField(null=True)
    opening_cash = models.DecimalField(max_digits=14, decimal_places=2)
    expected_cash = models.DecimalField(max_digits=14, decimal_places=2, null=True)
    counted_cash = models.DecimalField(max_digits=14, decimal_places=2, null=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=['terminal'], condition=Q(closed_at__isnull=True), name='one_open_shift_per_terminal'),
        ]


class Sale(AppendOnlyModel):
    # Generated by the till, so a retry after a dropped connection can't charge twice.
    client_uuid = models.UUIDField(unique=True)
    invoice_no = models.CharField(max_length=40, unique=True)
    branch = models.ForeignKey(Branch, on_delete=models.PROTECT)
    terminal = models.ForeignKey(Terminal, on_delete=models.PROTECT)
    shift = models.ForeignKey(Shift, on_delete=models.PROTECT, related_name='sales')
    cashier = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name='+')
    customer = models.ForeignKey('customers.Customer', null=True, blank=True, on_delete=models.PROTECT, related_name='sales')
    # Rung up while the server was unreachable and synced later; owners can review these.
    is_offline = models.BooleanField(default=False)
    subtotal = models.DecimalField(max_digits=14, decimal_places=2)
    discount = models.DecimalField(max_digits=14, decimal_places=2)
    tax = models.DecimalField(max_digits=14, decimal_places=2)
    total = models.DecimalField(max_digits=14, decimal_places=2)
    change_due = models.DecimalField(max_digits=14, decimal_places=2)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-id']
        indexes = [models.Index(fields=['branch', 'created_at'])]


class SaleLine(AppendOnlyModel):
    sale = models.ForeignKey(Sale, on_delete=models.PROTECT, related_name='lines')
    product = models.ForeignKey(Product, on_delete=models.PROTECT)
    # Copied at sale time: later price or name edits must not rewrite old invoices.
    name = models.CharField(max_length=255)
    barcode = models.CharField(max_length=64)
    pct_code = models.CharField(max_length=20, blank=True)
    quantity = models.DecimalField(max_digits=12, decimal_places=3)
    unit_price = models.DecimalField(max_digits=14, decimal_places=2)
    unit_cost = models.DecimalField(max_digits=14, decimal_places=2)
    discount = models.DecimalField(max_digits=14, decimal_places=2)
    tax_rate = models.DecimalField(max_digits=5, decimal_places=2)
    tax_amount = models.DecimalField(max_digits=14, decimal_places=2)
    line_total = models.DecimalField(max_digits=14, decimal_places=2)


class Payment(AppendOnlyModel):
    class Method(models.TextChoices):
        CASH = 'cash', 'Cash'
        JAZZCASH = 'jazzcash', 'JazzCash'
        EASYPAISA = 'easypaisa', 'Easypaisa'
        CARD = 'card', 'Card'
        CREDIT = 'credit', 'Customer credit'
        # Recorded payment method only — not a live Raast integration.
        RAAST = 'raast', 'Raast'

    sale = models.ForeignKey(Sale, on_delete=models.PROTECT, related_name='payments')
    method = models.CharField(max_length=20, choices=Method.choices)
    amount = models.DecimalField(max_digits=14, decimal_places=2)
    reference = models.CharField(max_length=100, blank=True)


class SaleReturn(AppendOnlyModel):
    client_uuid = models.UUIDField(unique=True)
    number = models.CharField(max_length=40, unique=True)
    # Null = walk-in return without the original invoice.
    sale = models.ForeignKey(Sale, null=True, blank=True, on_delete=models.PROTECT, related_name='returns')
    terminal = models.ForeignKey(Terminal, on_delete=models.PROTECT)
    # Set for cash refunds, which come out of that shift's drawer.
    shift = models.ForeignKey(Shift, null=True, blank=True, on_delete=models.PROTECT, related_name='returns')
    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name='+')
    method = models.CharField(max_length=20, choices=Payment.Method.choices)
    reason = models.CharField(max_length=255, blank=True)
    total = models.DecimalField(max_digits=14, decimal_places=2)
    tax = models.DecimalField(max_digits=14, decimal_places=2)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-id']


class ReturnLine(AppendOnlyModel):
    sale_return = models.ForeignKey(SaleReturn, on_delete=models.PROTECT, related_name='lines')
    # Null when returning without an invoice (product + unit_price used instead).
    sale_line = models.ForeignKey(SaleLine, null=True, blank=True, on_delete=models.PROTECT, related_name='return_lines')
    product = models.ForeignKey(Product, null=True, blank=True, on_delete=models.PROTECT, related_name='+')
    unit_price = models.DecimalField(max_digits=14, decimal_places=2, null=True, blank=True)
    quantity = models.DecimalField(max_digits=12, decimal_places=3)
    amount = models.DecimalField(max_digits=14, decimal_places=2)
    tax_amount = models.DecimalField(max_digits=14, decimal_places=2)
    restocked = models.BooleanField(default=True)
